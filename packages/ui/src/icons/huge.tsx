/** One Hugeicons glyph: decorative (`aria-hidden`) unless it carries an `aria-label`, then an image by that name. */
export function Icon({
  icon,
  className,
  strokeWidth = 1.75,
  size,
  "aria-label": label,
}: {
  icon: IconSvgElement;
  className?: string | undefined;
  strokeWidth?: number;
  size?: number;
  "aria-label"?: string;
}) {
  return (
    <HugeiconsIcon
      icon={icon}
      strokeWidth={strokeWidth}
      className={className}
      {...(size === undefined ? {} : { size })}
      {...(label ? { role: "img", "aria-label": label } : { "aria-hidden": true })}
    />
  );
}

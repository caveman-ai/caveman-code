/**
 * The ring: every agent state the sidebar animates is drawn on one ring of eight 2x2 dots, clockwise from
 * twelve (STYLE.md 8, "The ring"). Held frames and drawn tints, never a fade.
 *
 * It turns in half steps, two frames a dot, so a comet glides instead of jumping a whole dot at a time: between dots
 * the next one lights up a tint ahead of the head as the tail's last tint goes out, so the ring holds the same amount of
 * ink at every frame and never pulses.
 *
 * Working: the lit dot runs round with a tail of two tints behind it, the rest of the ring faint.
 * Agents at work: shorter comets chase each other round it, one for each agent at work from two up to four
 * (two, three, four or more), evenly spaced as the eight dots allow.
 * Stopped: the ring halts, flashes, pulses a pixel out and back, and closes on a stop square at its centre.
 * Done: the comet runs the ring closed, it turns green and fills in as the done mark.
 */
const RING = [[7, 2], [11, 3], [12, 7], [11, 11], [7, 12], [3, 11], [2, 7], [3, 3]] as const;
// The same ring a pixel further out: the stop's pulse.
const RING_OUT = [[7, 1], [12, 2], [13, 7], [12, 12], [7, 13], [2, 12], [1, 7], [2, 2]] as const;
const ringFrame = (tint: (dot: number) => string, dots: ReadonlyArray<readonly [number, number]> = RING, under?: string[]) => {
  const rows = (under ?? Array.from({ length: 16 }, () => "................")).map((r) => [...r]);
  dots.forEach(([x, y], i) => {
    const ch = tint(i);
    for (const [dx, dy] of [[0, 0], [1, 0], [0, 1], [1, 1]] as const) if (rows[y + dy]![x + dx] === ".") rows[y + dy]![x + dx] = ch;
  });
  return rows.map((r) => r.join(""));
};
const HALF_STEPS = RING.length * 2;
/** Brightest first: where comets overlap, the brighter tint wins. */
const TINTS = [INK, DIM, SHADE, FAINT];
/**
 * `n` heads spaced round the ring as evenly as eight dots allow, a frame per half step. `trail` tints a dot by how
 * far a head has passed it, in half steps from -1 (half a dot short, about to light) on; past the trail it's faint.
 */
const turning = (n: number, trail: string[]) => {
  const heads = Array.from({ length: n }, (_, i) => Math.round((i * RING.length) / n) * 2);
  return Array.from({ length: HALF_STEPS }, (_, step) =>
    ringFrame((dot) => {
      const tints = heads.map((h) => trail[((h + step - dot * 2 + 1 + HALF_STEPS) % HALF_STEPS)] ?? FAINT);
      return TINTS.find((t) => tints.includes(t)) ?? FAINT;
    }),
  );
};
// On a dot: the head and two tints behind. Between dots: the next dot a shade ahead, the head, one tint behind.
const WORK = turning(1, [SHADE, INK, INK, DIM, DIM, SHADE]);
/** Comets: a head and a one-dot tail each. */
const AGENTS = turning(2, [SHADE, INK, INK, SHADE]);
const AGENTS_3 = turning(3, [SHADE, INK, INK, SHADE]);
// Four comets two dots apart: half a step on, every dot is as far from a head as from a tail, so the in-between frame
// is the even crossfade, the whole ring dim, the same ink as the frames either side.
const AGENTS_4 = turning(4, [DIM, INK, DIM, SHADE]);
const square = (size: number) => {
  const rows = Array.from({ length: 16 }, () => [..."................"]);
  const at = 8 - size / 2;
  for (let y = at; y < at + size; y++) for (let x = at; x < at + size; x++) rows[y]![x] = INK;
  return rows.map((r) => r.join(""));
};

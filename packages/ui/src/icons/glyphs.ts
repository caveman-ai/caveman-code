export type GlyphPath = { char: string; d: string };

/** An icon arriving: a quarter of its pixels, half, three quarters, all of it. The last frame is the glyph. */
export function appearFrames(grid: string[]): string[][] {
  return [4, 8, 12, 16].map((t) => grid.map((row, y) => [...row].map((ch, x) => (BAYER[y % 4]![x % 4]! < t ? ch : ".")).join("")));
}

/** One path per colour: horizontal runs `M x y h w v 1 h -w z`, row by row. */
export function glyphPaths(grid: string[], dx = 0): GlyphPath[] {
  const byChar = new Map<string, string[]>();
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x]!;
      let end = x + 1;
      while (end < row.length && row[end] === ch) end++;
      if (ch !== ".") {
        const runs = byChar.get(ch) ?? [];
        runs.push(`M${x + dx} ${y}h${end - x}v1h-${end - x}z`);
        byChar.set(ch, runs);
      }
      x = end;
    }
  });
  return [...byChar].map(([char, runs]) => ({ char, d: runs.join("") }));
}

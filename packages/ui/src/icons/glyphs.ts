// ── Engine tiles: notched tint + a two-letter monogram in the sprite outline.
const LETTERS: Record<string, string[]> = {
  C: [".kkk.", "k...k", "k....", "k....", "k...k", ".kkk."],
  A: [".kkk.", "k...k", "k...k", "kkkkk", "k...k", "k...k"],
  X: ["k...k", ".k.k.", "..k..", "..k..", ".k.k.", "k...k"],
};
function tile(tint: string, left: string, right: string): string[] {
  const fill = (row: string) => row.replaceAll(".", tint);
  return Array.from({ length: 16 }, (_, y) => {
    const notch = y === 0 || y === 15;
    if (y < 5 || y > 10) return notch ? `.${tint.repeat(14)}.` : tint.repeat(16);
    const i = y - 5;
    return `${tint.repeat(2)}${fill(LETTERS[left]![i]!)}${tint.repeat(2)}${fill(LETTERS[right]![i]!)}${tint.repeat(2)}`;
  });
}


/** A 12px ring on rows 2-13 with `inner` (rows 2-13, 12 strings) laid over it. */
function inRing(inner: string): string[] {
  const over = g(inner);
  return Array.from({ length: 16 }, (_, y) => {
    if (y < 2 || y > 13) return ".".repeat(16);
    const ring = RING_12[y - 2]!;
    const top = over[y - 2]!;
    return [...ring].map((ch, x) => (top[x] !== "." ? top[x] : ch)).join("");
  });
}


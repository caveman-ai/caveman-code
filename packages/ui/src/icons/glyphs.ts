/** An ordered 4x4 dither: a pixel shows from the frame its threshold passes. */
const BAYER = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5],
] as const;

/** Done, landing: the comet runs the ring closed, the ring turns green, and the end mark dithers in over it. */
const finishing = (done: string[]) => {
  const lit = (upTo: number) => ringFrame((dot) => (dot <= upTo ? INK : FAINT));
  const green = (under?: string[]) => ringFrame(() => "v", RING, under);
  return [lit(2), lit(5), lit(7), green(), ...appearFrames(done).slice(0, 3).map((f) => green(f)), done];
};

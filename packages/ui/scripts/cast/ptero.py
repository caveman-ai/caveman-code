def right(w):
  return at(flip(w), 14)


def ptero(h=None, wl=WING, wr=None, dy=0, fxs=()):
  h = head() if h is None else h
  wr = right(wl) if wr is None else wr
  return stack(24, *(at(p, 0, dy) for p in (wl, wr, BODY_, h)), *fxs)


SPARKS = fx(24, [(0, 17, '*'), (5, 18, '*'), (0, 15, '*'), (6, 20, '*')])

"""The pterodactyl: wrong era like the dino, doesn't care either. It flies:
long leathery wings spread wide (a bony leading edge lit in ginger-hi, a
bone knuckle at the wrist, a ginger membrane with a scalloped trailing edge),
a small body and little feet hanging below, hovering a pixel off the floor.
The head is in profile, facing left: a long bone beak and a tunic crest
sweeping back make one long line, the green bead a band at the crest's base.
No skin: a skin tone never touches it."""

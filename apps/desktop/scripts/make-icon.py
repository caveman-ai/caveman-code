"""Builds resources/icon.{svg,png,icns,ico}: the Caveman flame, the brand's
8x8 pixel mark (FLAME in Caveman Cloud cloud/web/components/loaders/pixel.tsx),
white on a near-black plate.

The plate follows Apple's macOS grid: a 1024 canvas, an 824 square with
continuous corners (radius 185.4) inset 100 on every side, and the
template's shadow (28px blur, 12px down, 50% black). Its gradient is the
dark system icons' (#1f1f21 to #121213). There is no drawn highlight or rim:
Apple's guidelines leave those to the system. The flame keeps the brand
tile's proportions (3-unit cells, 1-unit gutters) and is 70% of the plate's
height, centred. Windows gets the same plate, cropped close (icon.ico: 16 to
48 px as 32-bit bitmaps, which every Windows tool and NSIS read, and 256 px
as PNG).

Needs python3, rsvg-convert (brew install librsvg) and macOS iconutil.
"""
import os
import shutil
import struct
import subprocess
import tempfile
import zlib

PLATE = ('#1f1f21', '#121213')  # the plate's top and bottom
FLAME = [
  '00011000',
  '00111100',
  '00111100',
  '01100110',
  '01100110',
  '11000011',
  '01100110',
  '00111100',
]
HEIGHT = 0.70  # the flame's height as a share of the plate's

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'resources')


def squircle(x, y, size, r):
  """A square with Apple's continuous corners (the curve starts 1.53r from each corner), as path data."""
  k = [v * r for v in (1.52866483, 1.08849323, 0.86840689, 0.63149399, 0.37282383, 0.16905956, 0.07491139)]
  a, b, c, d, e, f, g = k
  R, B = x + size, y + size
  return (
    f'M{x + a},{y} L{R - a},{y} C{R - b},{y} {R - c},{y} {R - d},{y + g} C{R - e},{y + f} {R - f},{y + e} {R - g},{y + d} '
    f'C{R},{y + c} {R},{y + b} {R},{y + a} L{R},{B - a} C{R},{B - b} {R},{B - c} {R - g},{B - d} '
    f'C{R - f},{B - e} {R - e},{B - f} {R - d},{B - g} C{R - c},{B} {R - b},{B} {R - a},{B} L{x + a},{B} '
    f'C{x + b},{B} {x + c},{B} {x + d},{B - g} C{x + e},{B - f} {x + f},{B - e} {x + g},{B - d} '
    f'C{x},{B - c} {x},{B - b} {x},{B - a} L{x},{y + a} C{x},{y + b} {x},{y + c} {x + g},{y + d} '
    f'C{x + f},{y + e} {x + e},{y + f} {x + d},{y + g} C{x + c},{y} {x + b},{y} {x + a},{y} Z'
  )


def svg():
  unit = HEIGHT * 824 / 31  # 8 cells of 3 units with 7 gutters of 1
  x0 = y0 = 512 - 31 * unit / 2
  cells = ''.join(
    f'<rect x="{x0 + x * 4 * unit:.2f}" y="{y0 + y * 4 * unit:.2f}" width="{3 * unit:.2f}" height="{3 * unit:.2f}" rx="{unit / 2:.2f}"/>'
    for y, row in enumerate(FLAME) for x, c in enumerate(row) if c == '1'
  )
  plate = squircle(100, 100, 824, 185.4)
  top, bottom = PLATE
  return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
<!-- Generated by scripts/make-icon.py. Do not edit by hand. -->
<defs>
<filter id="drop" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur in="SourceAlpha" stdDeviation="14"/><feOffset dy="12"/><feComponentTransfer><feFuncA type="linear" slope=".5"/></feComponentTransfer><feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge></filter>
<linearGradient id="charcoal" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{top}"/><stop offset="1" stop-color="{bottom}"/></linearGradient>
</defs>
<path d="{plate}" fill="{bottom}" filter="url(#drop)"/>
<path d="{plate}" fill="url(#charcoal)"/>
<g fill="#ffffff">{cells}</g>
</svg>
'''


def rgba(png):
  """The pixels of an 8-bit RGBA, non-interlaced PNG (what rsvg-convert writes), as rows of bytes."""
  assert png[:8] == b'\x89PNG\r\n\x1a\n'
  pos, idat, w, h = 8, b'', 0, 0
  while pos < len(png):
    length, kind = struct.unpack('>I4s', png[pos:pos + 8])
    data = png[pos + 8:pos + 8 + length]
    if kind == b'IHDR':
      w, h, depth, color, _, _, interlace = struct.unpack('>IIBBBBB', data)
      assert (depth, color, interlace) == (8, 6, 0), 'expected 8-bit RGBA, not interlaced'
    elif kind == b'IDAT':
      idat += data
    pos += 12 + length
  raw, stride, rows, prev = zlib.decompress(idat), w * 4, [], bytearray(w * 4)
  for y in range(h):
    kind, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
    for x in range(stride):
      a = line[x - 4] if x >= 4 else 0
      b = prev[x]
      c = prev[x - 4] if x >= 4 else 0
      if kind == 1:
        line[x] = (line[x] + a) & 255
      elif kind == 2:
        line[x] = (line[x] + b) & 255
      elif kind == 3:
        line[x] = (line[x] + (a + b) // 2) & 255
      elif kind == 4:
        p = a + b - c
        pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
        line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
    rows.append(bytes(line))
    prev = line
  return w, h, rows


def bitmap(png):
  """An icon directory image as a 32-bit DIB: BGRA rows bottom up, then an empty AND mask (alpha decides)."""
  w, h, rows = rgba(png)
  pixels = b''.join(bytes(b for i in range(0, len(row), 4) for b in (row[i + 2], row[i + 1], row[i], row[i + 3])) for row in reversed(rows))
  mask = bytes(((w + 31) // 32) * 4 * h)
  return struct.pack('<IiiHHIIiiII', 40, w, h * 2, 1, 32, 0, len(pixels) + len(mask), 0, 0, 0, 0) + pixels + mask


def ico(icon_svg, tmp):
  """resources/icon.ico from the plate cropped close: Windows draws icons edge to edge."""
  cropped = os.path.join(tmp, 'icon-win.svg')
  with open(icon_svg) as f:
    svg_text = f.read().replace('viewBox="0 0 1024 1024"', 'viewBox="80 80 864 864"', 1)
  with open(cropped, 'w') as f:
    f.write(svg_text)
  images = []
  for size in (16, 24, 32, 48, 64, 128, 256):
    out = os.path.join(tmp, f'win-{size}.png')
    subprocess.run(['rsvg-convert', '-w', str(size), '-h', str(size), cropped, '-o', out], check=True)
    with open(out, 'rb') as f:
      png = f.read()
    images.append((size, png if size == 256 else bitmap(png)))
  offset = 6 + 16 * len(images)
  head = struct.pack('<HHH', 0, 1, len(images))
  for size, data in images:
    head += struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(data), offset)
    offset += len(data)
  with open(os.path.join(OUT, 'icon.ico'), 'wb') as f:
    f.write(head + b''.join(data for _, data in images))


def main():
  icon_svg = os.path.join(OUT, 'icon.svg')
  with open(icon_svg, 'w') as f:
    f.write(svg())
  tmp = tempfile.mkdtemp()
  try:
    iconset = os.path.join(tmp, 'icon.iconset')
    os.mkdir(iconset)
    for size in (16, 32, 128, 256, 512):
      for scale, suffix in ((1, ''), (2, '@2x')):
        px = str(size * scale)
        subprocess.run(['rsvg-convert', '-w', px, '-h', px, icon_svg, '-o', os.path.join(iconset, f'icon_{size}x{size}{suffix}.png')], check=True)
    shutil.copy(os.path.join(iconset, 'icon_512x512.png'), os.path.join(OUT, 'icon.png'))
    subprocess.run(['iconutil', '-c', 'icns', iconset, '-o', os.path.join(OUT, 'icon.icns')], check=True)
    ico(icon_svg, tmp)
  finally:
    shutil.rmtree(tmp)
  for name in ('icon.svg', 'icon.png', 'icon.icns', 'icon.ico'):
    print(name, os.path.getsize(os.path.join(OUT, name)))


if __name__ == '__main__':
  main()

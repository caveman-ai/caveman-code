/** Pierre's extension table, for the languages above (the complete set: a .tsx or .jsx file wears React's mark). */
const BY_EXTENSION: Record<string, string> = {
  ts: "typescript", mts: "typescript", cts: "typescript", tsx: "react", jsx: "react",
  js: "javascript", mjs: "javascript", cjs: "javascript",
  css: "css", less: "css", postcss: "css",
  sql: "database", sqlite: "database",
  md: "markdown", mdx: "markdown", markdown: "markdown",
  json: "json", jsonc: "json", json5: "json", jsonl: "json",
  go: "go",
  sh: "bash", bash: "bash", zsh: "bash", ksh: "bash",
};

/** A fence's language, read as the extension it would have ("typescript" is a .ts file, "shell" a .sh one). */
const BY_LANGUAGE: Record<string, string> = {
  typescript: "typescript", javascript: "javascript", golang: "go", shell: "bash", console: "bash", postgres: "database", postgresql: "database",
};

/** The mark a file or a fence's language wears: its type's, or the plain file. */
export function fileType(pathOrLanguage: string): string {
  const name = pathOrLanguage.toLowerCase();
  const ext = name.includes(".") ? name.slice(name.lastIndexOf(".") + 1) : name;
  return BY_EXTENSION[ext] ?? BY_LANGUAGE[ext] ?? "default";
}

export function FileTypeMark({ path, size = 15 }: { /** A file's path, or a code fence's language. */ path: string; size?: number }) {
  const { dark } = useTheme();
  const mark = MARKS[fileType(path)] ?? MARKS.default!;
  const color = mark.color[dark ? 1 : 0];
  return (
    <Svg width={size} height={size} viewBox="0 0 16 16">
      {mark.paths.map((p, i) => (
        <Path key={i} d={p.d} fill={color} opacity={p.faint} fillRule={p.evenodd ? "evenodd" : undefined} clipRule={p.evenodd ? "evenodd" : undefined} />
      ))}
    </Svg>
  );
}
